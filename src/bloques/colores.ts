export function colorDe(base: string): string {
  const fila = TABLA.find(([patron]) => patron.test(base));
  if (fila) return fila[1];
  // Lo desconocido recibe un tono apagado pero fijo, para que dos bloques distintos no se confundan
  let h = 0;
  for (const c of base) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return `hsl(${h % 360} 25% 50%)`;
}
